package de.gematik.wsdl2openapi

import com.squareup.kotlinpoet.AnnotationSpec
import com.squareup.kotlinpoet.BOOLEAN
import com.squareup.kotlinpoet.ClassName
import com.squareup.kotlinpoet.DOUBLE
import com.squareup.kotlinpoet.FileSpec
import com.squareup.kotlinpoet.FunSpec
import com.squareup.kotlinpoet.INT
import com.squareup.kotlinpoet.KModifier
import com.squareup.kotlinpoet.LIST
import com.squareup.kotlinpoet.ParameterSpec
import com.squareup.kotlinpoet.ParameterizedTypeName.Companion.parameterizedBy
import com.squareup.kotlinpoet.PropertySpec
import com.squareup.kotlinpoet.STRING
import com.squareup.kotlinpoet.TypeName
import com.squareup.kotlinpoet.TypeSpec
import kotlinx.serialization.json.JsonObject

/**
 * Resolved type pointer — analogous to Go's `TypePointer`. Carries the fully
 * resolved [view] and, for `$ref` entries, the destination [qualPackage] /
 * [qualName] used when emitting cross-package references.
 */
data class TypePtr(
    val packageName: String,
    val view: TypeView,
    val xml: XmlExtension?,
    val qualPackage: String?,
    val qualName: String?,
    val isBase: Boolean,
    val nullable: Boolean,
    val refXml: XmlExtension?,
)

class Generator(
    private val outputDir: String,
    private val naming: NamingStrategy,
    private var api: Api,
) {
    private val schemas: Map<String, JsonObject>
        get() = api.components.schemas.entries.associate { (k, v) -> k to (v as JsonObject) }

    fun generate() {
        api = extractInlineObjects(api, naming)
        validate()
        java.io.File(outputDir).mkdirs()
        generateTypes()
        generateSoap()
    }

    private fun validate() {
        require(outputDir.isNotEmpty()) { "output directory is required" }
        for ((key, value) in schemas) validateRefs(value, key)
    }

    private fun validateRefs(node: JsonObject, ownerKey: String) {
        val ref = node["\$ref"]?.stringOrNull()
        if (ref != null) {
            val target = ref.removePrefix("#/components/schemas/")
            require(schemas.containsKey(target)) { "invalid reference in $ownerKey: $ref" }
        }
        (node["properties"] as? JsonObject)?.values?.forEach {
            (it as? JsonObject)?.let { o -> validateRefs(o, ownerKey) }
        }
        (node["items"] as? JsonObject)?.let { validateRefs(it, ownerKey) }
    }

    // --- Types -----------------------------------------------------------------

    private fun generateTypes() {
        for (key in schemas.keys) {
            val (pkg, type) = splitSchemaKey(key)
            require(pkg.isNotEmpty()) { "invalid schema key '$key' (missing '.' separator)" }
            generateType(pkg, type)
        }
    }

    /** Emits a single top-level type into `<TypeName>.kt`. Idiomatic Kotlin. */
    private fun generateType(pkgName: String, typeName: String) {
        val raw = schemas["$pkgName$SCHEMA_KEY_SEPARATOR$typeName"] ?: return
        val ptr = parseType(pkgName, raw) ?: return
        val kotlinPackage = naming.buildPackagePath(pkgName)
        val file = FileSpec.builder(kotlinPackage, typeName)
            .addFileComment("Code generated by wsdl2openapi; DO NOT EDIT.")
        when {
            ptr.view.isObject -> {
                emitObject(file, typeName, ptr)
                writeFile(file.build(), pkgName, "$typeName.kt")
            }
            ptr.view.isPrimitive && ptr.view.enum != null -> {
                emitEnum(file, typeName, ptr)
                writeFile(file.build(), pkgName, "$typeName.kt")
            }
            // pure primitives without facets are rendered inline at the use site
            else -> Unit
        }
    }

    private fun emitObject(fileBuilder: FileSpec.Builder, typeName: String, ptr: TypePtr) {
        val classBuilder = TypeSpec.classBuilder(typeName)
            .addModifiers(KModifier.DATA)
            .addAnnotation(serializableAnnotation())

        ptr.xml?.takeIf { it.name.isNotEmpty() }?.let { x ->
            classBuilder.addAnnotation(xmlSerialNameAnnotation(x.name, x.namespace, x.prefix))
        }

        val ctor = FunSpec.constructorBuilder()
        val props = ptr.view.properties ?: JsonObject(emptyMap())
        val requiredSet = ptr.view.required.toSet()

        for ((propName, propEl) in props.entries) {
            val propObj = propEl as? JsonObject ?: continue
            val propPtr = parseType(ptr.packageName, propObj) ?: continue
            val effective = propPtr.copy(nullable = propName !in requiredSet)
            val (paramSpec, fieldSpec) = renderProperty(ptr, propName, effective)
            ctor.addParameter(paramSpec)
            classBuilder.addProperty(fieldSpec)
        }

        classBuilder.primaryConstructor(ctor.build())
        fileBuilder.addType(classBuilder.build())
    }

    private fun emitEnum(fileBuilder: FileSpec.Builder, typeName: String, ptr: TypePtr) {
        val enumValues = ptr.view.enum ?: return
        val enumBuilder = TypeSpec.enumBuilder(typeName)
            .addAnnotation(serializableAnnotation())
        for (v in enumValues) {
            val constName = naming.publicIdentifier(v).ifBlank { "VALUE_$v" }
            enumBuilder.addEnumConstant(
                constName,
                TypeSpec.anonymousClassBuilder()
                    .addAnnotation(
                        AnnotationSpec.builder(ClassName("kotlinx.serialization", "SerialName"))
                            .addMember("%S", v).build()
                    ).build()
            )
        }
        fileBuilder.addType(enumBuilder.build())
    }

    /** Returns (parameterSpec, propertySpec) for a primary-constructor field. */
    private fun renderProperty(
        ownerPtr: TypePtr,
        propName: String,
        propPtr: TypePtr,
    ): Pair<ParameterSpec, PropertySpec> {
        val fieldName = camelCase(propName)
        val isArray = propPtr.view.isArray

        var elementPtr = propPtr
        if (isArray) {
            val itemsRaw = propPtr.view.items as? JsonObject
            if (itemsRaw != null) elementPtr = parseType(propPtr.packageName, itemsRaw) ?: propPtr
        }

        val baseType: TypeName = resolveTypeName(elementPtr)
        val effectiveType: TypeName = if (isArray) LIST.parameterizedBy(baseType) else baseType
        val nullable = propPtr.nullable && !isArray
        val finalType = if (nullable) effectiveType.copy(nullable = true) else effectiveType

        val annotations = mutableListOf<AnnotationSpec>()
        val xmlExt = elementPtr.refXml ?: elementPtr.xml
        val sameNamespace = ownerPtr.xml?.namespace.orEmpty().isNotEmpty() &&
            ownerPtr.xml?.namespace == xmlExt?.namespace

        val isAttribute = xmlExt?.attribute == true
        annotations += AnnotationSpec.builder(ClassName("nl.adaptivity.xmlutil.serialization", "XmlElement"))
            .addMember(if (isAttribute) "false" else "true").build()

        if (xmlExt != null && xmlExt.name.isNotEmpty()) {
            val ns = if (!sameNamespace) xmlExt.namespace else ""
            annotations += xmlSerialNameAnnotation(xmlExt.name, ns, xmlExt.prefix)
        }

        val paramBuilder = ParameterSpec.builder(fieldName, finalType)
        if (nullable) paramBuilder.defaultValue("null")
        else if (isArray) paramBuilder.defaultValue("emptyList()")

        val propSpec = PropertySpec.builder(fieldName, finalType)
            .initializer(fieldName)
            .also { spec -> annotations.forEach { spec.addAnnotation(it) } }
            .build()

        return paramBuilder.build() to propSpec
    }

    private fun resolveTypeName(ptr: TypePtr): TypeName {
        if (ptr.qualPackage != null && ptr.qualName != null) {
            return if (isPrimitiveWithoutFacets(ptr)) primitiveType(ptr.view)
            else ClassName(ptr.qualPackage, ptr.qualName)
        }
        return when (ptr.view.type) {
            "string" -> STRING
            "integer" -> INT
            "number" -> DOUBLE
            "boolean" -> BOOLEAN
            "object" -> ClassName("kotlin", "Any") // shouldn't normally hit after extraction
            else -> STRING
        }
    }

    private fun isPrimitiveWithoutFacets(ptr: TypePtr): Boolean =
        ptr.view.isPrimitive && ptr.view.enum == null

    private fun primitiveType(view: TypeView): TypeName = when (view.type) {
        "string" -> STRING
        "integer" -> INT
        "number" -> DOUBLE
        "boolean" -> BOOLEAN
        else -> STRING
    }

    /**
     * Resolve a raw schema fragment to a [TypePtr]. Refs are followed once;
     * the result carries the resolved [view] and qualified name needed for
     * cross-package references. A ref's own xml extension overrides the
     * target's (mirrors Go's parseRef behaviour).
     */
    fun parseType(schemaPkg: String, raw: JsonObject): TypePtr? {
        val ref = raw["\$ref"]?.stringOrNull()
        if (ref != null) {
            val targetKey = ref.removePrefix("#/components/schemas/")
            val target = schemas[targetKey] ?: return null
            val (targetPkg, targetName) = splitSchemaKey(targetKey)
            val targetPtr = parseType(targetPkg, target) ?: return null
            val refXmlObj = raw["xml"] as? JsonObject
            val refXml = refXmlObj?.let { JSON.decodeFromJsonElement(XmlExtension.serializer(), it) }
            return targetPtr.copy(
                qualPackage = naming.buildPackagePath(targetPkg),
                qualName = targetName,
                refXml = refXml,
                xml = refXml ?: targetPtr.xml,
                isBase = refXml?.isBase ?: targetPtr.isBase,
            )
        }
        val view = TypeView(raw)
        val xml = view.xml
        return TypePtr(
            packageName = schemaPkg,
            view = view,
            xml = xml,
            qualPackage = null,
            qualName = null,
            isBase = xml?.isBase == true,
            nullable = false,
            refXml = null,
        )
    }

    // --- SOAP -----------------------------------------------------------------

    /**
     * Package that holds the shared `SoapEnvelope` interface + `SoapOperation`
     * data class. Anchored under `<basePackage>.soap`, or just `soap` if no
     * basePackage was configured.
     */
    private fun sharedSoapPackage(): String {
        val base = naming.basePackage
            .replace('/', '.').replace('\\', '.').replace("-", "")
            .lowercase().trim('.')
        return if (base.isEmpty()) "soap" else "$base.soap"
    }

    private val soapEnvelopeCn get() = ClassName(sharedSoapPackage(), "SoapEnvelope")
    private val soapOperationCn get() = ClassName(sharedSoapPackage(), "SoapOperation")

    private fun generateSoap() {
        if (api.webServices.none { ws -> ws.ports.any { it.bindingType == BindingType.SOAP11 } }) return
        emitSharedSoapFile()
        for (ws in api.webServices) {
            for (port in ws.ports) {
                if (port.bindingType != BindingType.SOAP11) continue
                val portPkgName = naming.packageForPort(ws, port)
                generatePortFiles(portPkgName, port)
            }
        }
    }

    /**
     * Emits the single `SoapEnvelope.kt` shared by every generated port. Holds
     * the polymorphic envelope contract (`isFault()`) and the `SoapOperation`
     * metadata type. Idiomatic Kotlin polymorphism — consumers can deal with
     * any envelope generically without depending on a specific operation.
     */
    private fun emitSharedSoapFile() {
        val pkg = sharedSoapPackage()
        // Filesystem path: pkg as nested directories under outputDir.
        val file = FileSpec.builder(pkg, "SoapEnvelope")
            .addFileComment("Code generated by wsdl2openapi; DO NOT EDIT.")
            .addType(
                TypeSpec.interfaceBuilder("SoapEnvelope")
                    .addFunction(
                        FunSpec.builder("isFault")
                            .addModifiers(KModifier.ABSTRACT)
                            .returns(BOOLEAN).build()
                    ).build()
            )
            .addType(
                TypeSpec.classBuilder("SoapOperation")
                    .addModifiers(KModifier.DATA)
                    .primaryConstructor(
                        FunSpec.constructorBuilder()
                            .addParameter("name", STRING)
                            .addParameter("soapAction", STRING)
                            .addParameter("bindingType", STRING).build()
                    )
                    .addProperty(PropertySpec.builder("name", STRING).initializer("name").build())
                    .addProperty(PropertySpec.builder("soapAction", STRING).initializer("soapAction").build())
                    .addProperty(PropertySpec.builder("bindingType", STRING).initializer("bindingType").build())
                    .build()
            ).build()

        // Write directly: sharedSoapPackage isn't a wsdl namespace, so bypass
        // NamingStrategy.filePath (which would re-route through packageMappings).
        val pkgDir = pkg.split('.').fold(java.io.File(outputDir)) { acc, seg -> java.io.File(acc, seg) }
        pkgDir.mkdirs()
        java.io.File(pkgDir, "SoapEnvelope.kt").writeText(stripDefaultPublic(file.toString()))
    }

    /**
     * Generates four kinds of per-port files:
     * 1. `Operations.kt` — `object Operations { val Foo = SoapOperation(...) }`
     *    (references the shared [SoapOperation] type, no longer redefined here).
     * 2. `<PortName>.kt` — service interface declaring one typed method per
     *    operation; consumers implement this for their transport.
     * 3. `<Op>Envelope.kt` — request envelope.
     * 4. `<Op>ResponseEnvelope.kt` — response envelope (with optional fault).
     *
     * All envelope classes implement [SoapEnvelope], so callers can poll
     * `isFault()` without knowing the concrete operation type.
     */
    private fun generatePortFiles(portPkgName: String, port: WebServicePort) {
        val kotlinPackage = naming.buildPackagePath(portPkgName)
        val bindingTypeStr = bindingTypeWireValue(port.bindingType)

        // Operations.kt — metadata object only.
        val operationsFile = FileSpec.builder(kotlinPackage, "Operations")
            .addFileComment("Code generated by wsdl2openapi; DO NOT EDIT.")
        val operationsObj = TypeSpec.objectBuilder("Operations")
        for (op in port.operations) {
            operationsObj.addProperty(
                PropertySpec.builder(naming.publicIdentifier(op.name), soapOperationCn)
                    .initializer("%T(%S, %S, %S)", soapOperationCn, op.name, op.soapAction, bindingTypeStr)
                    .build()
            )
        }
        operationsFile.addType(operationsObj.build())
        writeFile(operationsFile.build(), portPkgName, "Operations.kt")

        // Per-operation envelope files + collect resolved body refs for the service interface.
        data class OpRefs(val op: OperationDefinition, val input: TypePtr, val output: TypePtr)
        val resolved = mutableListOf<OpRefs>()
        for (op in port.operations) {
            val inputBody = resolveBodyRef(op.input.soapBody) ?: continue
            val outputBody = resolveBodyRef(op.output.soapBody) ?: continue
            val faultBody = op.faults.values.firstOrNull()?.soapBody?.let { resolveBodyRef(it) }
            resolved += OpRefs(op, inputBody, outputBody)

            val inputName = naming.inputEnvelopeName(op)
            val inFile = FileSpec.builder(kotlinPackage, inputName)
                .addFileComment("Code generated by wsdl2openapi; DO NOT EDIT.")
                .addType(buildEnvelopeClass(kotlinPackage, inputName, inputBody, fault = null))
            writeFile(inFile.build(), portPkgName, "$inputName.kt")

            val outName = naming.outputEnvelopeName(op)
            val outFile = FileSpec.builder(kotlinPackage, outName)
                .addFileComment("Code generated by wsdl2openapi; DO NOT EDIT.")
                .addType(buildEnvelopeClass(kotlinPackage, outName, outputBody, fault = faultBody))
            writeFile(outFile.build(), portPkgName, "$outName.kt")
        }

        // <PortName>.kt — service interface mapping each operation to a typed method.
        val portInterfaceName = naming.normalizePortName(port.name)
        val portInterface = TypeSpec.interfaceBuilder(portInterfaceName)
        for ((op, input, output) in resolved) {
            val methodName = camelCase(op.name)
            val requestType = ClassName(input.qualPackage!!, input.qualName!!)
            val responseType = ClassName(output.qualPackage!!, output.qualName!!)
            portInterface.addFunction(
                FunSpec.builder(methodName)
                    .addModifiers(KModifier.ABSTRACT)
                    .addParameter("request", requestType)
                    .returns(responseType)
                    .build()
            )
        }
        val portFile = FileSpec.builder(kotlinPackage, portInterfaceName)
            .addFileComment("Code generated by wsdl2openapi; DO NOT EDIT.")
            .addType(portInterface.build())
            .build()
        writeFile(portFile, portPkgName, "$portInterfaceName.kt")
    }

    private fun bindingTypeWireValue(bt: BindingType): String = when (bt) {
        BindingType.SOAP11 -> "soap11"
        BindingType.SOAP12 -> "soap12"
        BindingType.HTTP_GET -> "http-get"
        BindingType.HTTP_POST -> "http-post"
        BindingType.OTHER -> "other"
    }

    private fun resolveBodyRef(ref: String): TypePtr? {
        val key = ref.removePrefix("#/components/schemas/")
        val raw = schemas[key] ?: return null
        val (pkg, name) = splitSchemaKey(key)
        val ptr = parseType(pkg, raw) ?: return null
        return ptr.copy(qualPackage = naming.buildPackagePath(pkg), qualName = name)
    }

    private fun buildEnvelopeClass(envelopePkg: String, envelopeName: String, body: TypePtr, fault: TypePtr?): TypeSpec {
        val envelopeNs = "http://schemas.xmlsoap.org/soap/envelope/"
        val cls = TypeSpec.classBuilder(envelopeName)
            .addModifiers(KModifier.DATA)
            .addAnnotation(serializableAnnotation())
            .addAnnotation(xmlSerialNameAnnotation("Envelope", envelopeNs, "SOAP-ENV"))
            .addSuperinterface(soapEnvelopeCn)

        val enclosingCn = ClassName(envelopePkg, envelopeName)
        val bodyCn = enclosingCn.nestedClass("Body")
        val faultCn = enclosingCn.nestedClass("Fault")
        val xmlElementAnnot = AnnotationSpec.builder(ClassName("nl.adaptivity.xmlutil.serialization", "XmlElement"))
            .addMember("true").build()

        cls.primaryConstructor(
            FunSpec.constructorBuilder().addParameter("body", bodyCn).build()
        )
        cls.addProperty(
            PropertySpec.builder("body", bodyCn)
                .initializer("body")
                .addAnnotation(xmlElementAnnot)
                .addAnnotation(xmlSerialNameAnnotation("Body", envelopeNs, "SOAP-ENV"))
                .build()
        )

        // Body
        val bodyCtor = FunSpec.constructorBuilder()
        val bodyType = ClassName(body.qualPackage!!, body.qualName!!).copy(nullable = true)
        val bodyFieldName = decapitalize(body.qualName)
        bodyCtor.addParameter(ParameterSpec.builder(bodyFieldName, bodyType).defaultValue("null").build())
        val bodyClassBuilder = TypeSpec.classBuilder("Body")
            .addModifiers(KModifier.DATA)
            .addAnnotation(serializableAnnotation())
            .addProperty(
                PropertySpec.builder(bodyFieldName, bodyType).initializer(bodyFieldName)
                    .addAnnotation(xmlElementAnnot).build()
            )
        if (fault != null) {
            bodyCtor.addParameter(
                ParameterSpec.builder("fault", faultCn.copy(nullable = true)).defaultValue("null").build()
            )
            bodyClassBuilder.addProperty(
                PropertySpec.builder("fault", faultCn.copy(nullable = true)).initializer("fault")
                    .addAnnotation(xmlElementAnnot)
                    .addAnnotation(xmlSerialNameAnnotation("Fault", envelopeNs, "SOAP-ENV"))
                    .build()
            )
        }
        bodyClassBuilder.primaryConstructor(bodyCtor.build())
        cls.addType(bodyClassBuilder.build())

        // Fault
        if (fault != null) {
            val detailType = ClassName(fault.qualPackage!!, fault.qualName!!).copy(nullable = true)
            cls.addType(
                TypeSpec.classBuilder("Fault")
                    .addModifiers(KModifier.DATA)
                    .addAnnotation(serializableAnnotation())
                    .primaryConstructor(
                        FunSpec.constructorBuilder()
                            .addParameter(ParameterSpec.builder("faultcode", STRING).defaultValue("\"\"").build())
                            .addParameter(ParameterSpec.builder("faultstring", STRING).defaultValue("\"\"").build())
                            .addParameter(ParameterSpec.builder("faultactor", STRING.copy(nullable = true)).defaultValue("null").build())
                            .addParameter(ParameterSpec.builder("detail", detailType).defaultValue("null").build())
                            .build()
                    )
                    .addProperty(PropertySpec.builder("faultcode", STRING).initializer("faultcode").addAnnotation(xmlElementAnnot).build())
                    .addProperty(PropertySpec.builder("faultstring", STRING).initializer("faultstring").addAnnotation(xmlElementAnnot).build())
                    .addProperty(PropertySpec.builder("faultactor", STRING.copy(nullable = true)).initializer("faultactor").addAnnotation(xmlElementAnnot).build())
                    .addProperty(PropertySpec.builder("detail", detailType).initializer("detail").addAnnotation(xmlElementAnnot).build())
                    .build()
            )
        }

        cls.addFunction(
            FunSpec.builder("isFault")
                .addModifiers(KModifier.OVERRIDE)
                .returns(BOOLEAN)
                .addStatement(if (fault != null) "return body.fault != null" else "return false")
                .build()
        )

        return cls.build()
    }

    // --- File output ---------------------------------------------------------

    /**
     * Writes a [FileSpec] to disk, stripping the redundant `public` modifier
     * that kotlinpoet 2.x emits by default. Idiomatic Kotlin omits explicit
     * public visibility everywhere it is the default.
     */
    private fun writeFile(file: FileSpec, pkgName: String, filename: String) {
        val target = naming.filePath(outputDir, pkgName, filename)
        target.parentFile.mkdirs()
        target.writeText(stripDefaultPublic(file.toString()))
    }

    private fun stripDefaultPublic(source: String): String =
        source.replace(Regex("""(?m)^(\s*)public\s+"""), "$1")

    private fun serializableAnnotation(): AnnotationSpec =
        AnnotationSpec.builder(ClassName("kotlinx.serialization", "Serializable")).build()

    private fun xmlSerialNameAnnotation(name: String, namespace: String, prefix: String): AnnotationSpec {
        val b = AnnotationSpec.builder(ClassName("nl.adaptivity.xmlutil.serialization", "XmlSerialName"))
            .addMember("%S", name)
        if (namespace.isNotEmpty()) b.addMember("namespace = %S", namespace)
        if (prefix.isNotEmpty()) b.addMember("prefix = %S", prefix)
        return b.build()
    }

    private fun camelCase(name: String): String {
        if (name.isEmpty()) return name
        val sanitized = name.map { c -> if (c.isLetterOrDigit()) c else '_' }.joinToString("")
        val parts = sanitized.split('_').filter { it.isNotEmpty() }
        if (parts.isEmpty()) return "_"
        val head = parts.first().replaceFirstChar(Char::lowercaseChar)
        val tail = parts.drop(1).joinToString("") { it.replaceFirstChar(Char::uppercaseChar) }
        var result = head + tail
        if (result.first().isDigit()) result = "_$result"
        return escapeKotlinKeyword(result)
    }

    private fun decapitalize(s: String): String =
        if (s.isEmpty()) s else escapeKotlinKeyword(s.replaceFirstChar(Char::lowercaseChar))

    private fun escapeKotlinKeyword(name: String): String =
        if (name in KOTLIN_HARD_KEYWORDS) "`$name`" else name

    private companion object {
        val KOTLIN_HARD_KEYWORDS = setOf(
            "as", "break", "class", "continue", "do", "else", "false", "for", "fun",
            "if", "in", "interface", "is", "null", "object", "package", "return",
            "super", "this", "throw", "true", "try", "typealias", "typeof", "val",
            "var", "when", "while",
        )
    }
}
