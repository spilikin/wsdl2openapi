use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::path::{Path, PathBuf};

use anyhow::{Context, Result};
use proc_macro2::TokenStream;
use quote::quote;

use crate::emit::ident;
use crate::ir::ModulePath;
use crate::naming::unraw;

pub const HEADER: &str = "// Code generated by wsdl2openapi; DO NOT EDIT.\n\n";

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct GeneratedFile {
    /// Path relative to the output directory.
    pub path: PathBuf,
    pub contents: String,
}

/// Collects items per module and lays them out as a module tree: `mod.rs` at
/// the root (so the directory can be mounted with `mod name;`), and
/// `name.rs` + `name/` below it.
#[derive(Default)]
pub struct ModuleTree {
    modules: BTreeMap<ModulePath, Vec<TokenStream>>,
}

impl ModuleTree {
    pub fn push(&mut self, module: &ModulePath, item: TokenStream) {
        for depth in 0..=module.len() {
            self.modules.entry(module[..depth].to_vec()).or_default();
        }
        self.modules
            .get_mut(module)
            .expect("module was just inserted")
            .push(item);
    }

    pub fn contains(&self, module: &ModulePath) -> bool {
        self.modules.contains_key(module)
    }

    pub fn into_files(self) -> Result<Vec<GeneratedFile>> {
        let mut children: BTreeMap<ModulePath, BTreeSet<String>> = BTreeMap::new();
        for module in self.modules.keys() {
            if let Some((last, parent)) = module.split_last() {
                children
                    .entry(parent.to_vec())
                    .or_default()
                    .insert(last.clone());
            }
        }
        self.modules
            .into_iter()
            .map(|(module, items)| {
                let mods = children
                    .get(&module)
                    .into_iter()
                    .flatten()
                    .map(|c| ident(c));
                let tokens = quote! {
                    #(pub mod #mods;)*
                    #(#items)*
                };
                Ok(GeneratedFile {
                    path: file_path(&module),
                    contents: render(tokens)
                        .with_context(|| format!("module {}", module.join("::")))?,
                })
            })
            .collect()
    }
}

fn file_path(module: &ModulePath) -> PathBuf {
    match module.split_last() {
        None => PathBuf::from("mod.rs"),
        Some((last, parents)) => {
            let mut path: PathBuf = parents.iter().map(|s| unraw(s)).collect();
            path.push(format!("{}.rs", unraw(last)));
            path
        }
    }
}

/// Formats a module with a blank line between items, which prettyplease
/// leaves out; consecutive `mod` declarations stay grouped.
pub fn render(tokens: TokenStream) -> Result<String> {
    let file: syn::File = syn::parse2(tokens).context("generated code does not parse")?;
    let mut out = String::from(HEADER);
    let mut previous_was_mod = false;
    for (i, item) in file.items.into_iter().enumerate() {
        let is_mod = matches!(item, syn::Item::Mod(_));
        if i > 0 && !(is_mod && previous_was_mod) {
            out.push('\n');
        }
        previous_was_mod = is_mod;
        let single = syn::File {
            shebang: None,
            frontmatter: None,
            attrs: Vec::new(),
            items: vec![item],
        };
        out.push_str(&prettyplease::unparse(&single));
    }
    Ok(out)
}

pub fn write_files(dir: &Path, files: &[GeneratedFile]) -> Result<()> {
    for file in files {
        let path = dir.join(&file.path);
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent).with_context(|| format!("creating {}", parent.display()))?;
        }
        fs::write(&path, &file.contents).with_context(|| format!("writing {}", path.display()))?;
    }
    Ok(())
}
