package main

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/dave/jennifer/jen"
)

type Qual struct {
	NamespaceId string
	Path        string
	Name        string
}

type TypePointer struct {
	NamespaceId string
	Type        TypeDefinition
	Xml         *XmlExtension
	Nullable    bool
	Ref         *ReferenceObject
	Qual        *Qual
	IsBase      bool
}

type Generator struct {
	OutputDir      string
	NamingStrategy NamingStrategy
	Api            *Api
}

func (g *Generator) Generate() error {
	if err := os.MkdirAll(g.OutputDir, 0755); err != nil {
		return err
	}

	if err := g.GenerateTypes(); err != nil {
		return err
	}

	return nil
}

func (g *Generator) GenerateTypes() error {
	for namespaceId, schema := range g.Api.Components.Schemas {
		schemaPath := g.NamingStrategy.FilenameForTypes(g.OutputDir, namespaceId)
		err := os.MkdirAll(filepath.Dir(schemaPath), 0755)
		if err != nil {
			return err
		}

		packagePath := g.NamingStrategy.BuildPackagePath(namespaceId)

		jenFile := jen.NewFilePath(packagePath)

		jenFile.HeaderComment("// Code generated by wsdl2openapi; DO NOT EDIT.")

		for typeName, typeRaw := range schema {
			typePtr, err := g.parseType(namespaceId, typeRaw)
			if err != nil {
				return fmt.Errorf("failed to parse type %s in schema %s: %w", typeName, namespaceId, err)
			}

			jenFile.Line()

			switch t := typePtr.Type.(type) {
			case *TypeObject:
				err := g.renderGlobalObject(jenFile, typePtr, typeName, t)
				if err != nil {
					return fmt.Errorf("failed to render struct for type %s in schema %s: %w", typeName, namespaceId, err)
				}
			case *TypeString:
				jenFile.Type().Id(typeName).String()
			default:
				return fmt.Errorf("unsupported type definition for type %s in schema %s: %T", typeName, namespaceId, typePtr.Type)
			}
		}
		err = jenFile.Save(schemaPath)
		if err != nil {
			return fmt.Errorf("failed to save generated types to %s: %w", schemaPath, err)
		}
	}
	return nil
}

func (g *Generator) renderGlobalObject(jenFile *jen.File, typePtr *TypePointer, typeName string, typeDef *TypeObject) error {

	fields, err := g.renderProperties(typePtr, typeDef)
	if err != nil {
		return fmt.Errorf("failed to render properties for type %s in namespace %s: %w", typeName, typePtr.NamespaceId, err)
	}
	jenFile.Type().Id(typeName).Struct(fields...)

	if typePtr.Xml != nil && len(typePtr.Xml.Extends) > 0 {
		for _, ext := range typePtr.Xml.Extends {
			jenFile.Comment("extends " + ext)
			jenFile.Func().Params(jen.Id(typeName)).Id(g.NamingStrategy.BaseTypeFuncName(ext)).Params().Block()
		}
	}

	if typeDef.Xml != nil && typeDef.Xml.IsBase {
		interfaceName := g.NamingStrategy.BaseTypeInterfaceName(typeName)
		funcName := g.NamingStrategy.BaseTypeFuncName(fmt.Sprintf("#/components/schemas/%s/%s", typePtr.NamespaceId, typeName))
		jenFile.Line()
		jenFile.Comment("Interface for types that extend " + typeName)
		jenFile.Type().Id(interfaceName).Interface(
			jen.Id(funcName).Params(),
		)
	}

	return nil
}

func (g *Generator) renderProperties(typePtr *TypePointer, typeDef *TypeObject) ([]jen.Code, error) {
	var fieldDefs []jen.Code

	if typePtr.Xml != nil && typePtr.Xml.Name != "" {
		x := jen.Id("XMLName").Qual("encoding/xml", "Name").Tag(map[string]string{
			"xml": fmt.Sprintf("%s %s", typePtr.Xml.Namespace, typePtr.Xml.Name),
		})
		fieldDefs = append(fieldDefs, x)
	}

	for propName, propTypeRaw := range typeDef.Properties {
		propType, err := g.parseType(typePtr.NamespaceId, propTypeRaw)
		if err != nil {
			return nil, fmt.Errorf("failed to parse property %s in namespace %s: %w", propName, typePtr.NamespaceId, err)
		}
		propertyCode, err := g.renderProperty(propName, propType)
		if err != nil {
			return nil, fmt.Errorf("failed to render property %s in namespace %s: %w", propName, typePtr.NamespaceId, err)
		}
		fieldDefs = append(fieldDefs, propertyCode)
	}

	return fieldDefs, nil
}

func (g *Generator) renderProperty(propName string, propType *TypePointer) (jen.Code, error) {
	fieldName := g.NamingStrategy.PublicFieldName(propName)

	stmt := jen.Id(fieldName)

	return g.renderPropertyTypeAndTags(stmt, propType)
}

func (g *Generator) renderPropertyTypeAndTags(stmt *jen.Statement, propPtr *TypePointer) (*jen.Statement, error) {
	isArray := false
	if typeArray, ok := propPtr.Type.(*TypeArray); ok {
		stmt = stmt.Op("[]")
		itemsTypePtr, err := g.parseType(propPtr.NamespaceId, typeArray.Items)
		if err != nil {
			return nil, err
		}
		propPtr = itemsTypePtr
		isArray = true
	}

	xmlExt := propPtr.Xml
	var xmlTag []string

	// create XML tag from xml extension
	if xmlExt != nil && xmlExt.Name != "" {
		if xmlExt.Namespace != "" {
			xmlTag = append(xmlTag, xmlExt.Namespace+" "+xmlExt.Name)
		} else {
			xmlTag = append(xmlTag, xmlExt.Name)
		}
		if xmlExt.Attribute {
			xmlTag = append(xmlTag, "attr")
		}
	}

	addOmitempty := func() {
		if propPtr.Nullable && len(xmlTag) > 0 {
			xmlTag = append(xmlTag, "omitempty")
		}
	}

	propType := propPtr.Type

	if propPtr.Qual != nil {
		// add pointer only for non-array, nullable, non-base types
		if !isArray && propPtr.Nullable && !propPtr.IsBase {
			stmt = stmt.Op("*")
			addOmitempty()
		}
		if propPtr.IsBase {
			interfaceName := g.NamingStrategy.BaseTypeInterfaceName(propPtr.Qual.Name)
			stmt = stmt.Qual(propPtr.Qual.Path, interfaceName)
		} else {
			stmt = stmt.Qual(propPtr.Qual.Path, propPtr.Qual.Name)
		}
	} else {
		switch t := propType.(type) {
		case *TypeString:
			stmt = stmt.String()
			if t.Format != nil && *t.Format == "chardata" {
				xmlTag = append(xmlTag, "chardata")
			}
			addOmitempty()
		case *TypeNumber:
			stmt = stmt.Float64()
		case *TypeInteger:
			stmt = stmt.Int()
		case *TypeBoolean:
			stmt = stmt.Bool()
		case *TypeObject:
			fields, err := g.renderProperties(propPtr, t)
			if err != nil {
				return nil, err
			}
			if !isArray && propPtr.Nullable {
				stmt = stmt.Op("*")
				addOmitempty()
			}
			stmt = stmt.Struct(fields...)
		default:
			return nil, fmt.Errorf("unsupported property type: %T", propType)
		}
	}

	tag := make(map[string]string)
	if len(xmlTag) > 0 {
		tag["xml"] = strings.Join(xmlTag, ",")
	}

	stmt = stmt.Tag(tag)

	return stmt, nil
}

func (g *Generator) resolveRef(ref string) (*Qual, *json.RawMessage, error) {
	if !strings.HasPrefix(ref, "#/components/schemas/") {
		return nil, nil, fmt.Errorf("unsupported ref format: %s", ref)
	}
	parts := strings.Split(ref[len("#/components/schemas/"):], "/")
	if len(parts) < 2 {
		return nil, nil, fmt.Errorf("invalid ref format: %s", ref)
	}
	namespaceId := parts[0]
	typeName := parts[1]

	schema, ok := g.Api.Components.Schemas[namespaceId]
	if !ok {
		return nil, nil, fmt.Errorf("schema not found: %s", namespaceId)
	}

	rawType, ok := schema[typeName]
	if !ok {
		return nil, nil, fmt.Errorf("type not found: %s", typeName)
	}

	qual := &Qual{
		NamespaceId: namespaceId,
		Path:        g.NamingStrategy.BuildPackagePath(namespaceId),
		Name:        typeName,
	}

	return qual, &rawType, nil
}

func (g *Generator) parseRef(raw json.RawMessage) (*TypePointer, error) {
	refObj := new(ReferenceObject)
	err := json.Unmarshal(raw, refObj)
	if err != nil {
		return nil, err
	}
	qual, rawType, err := g.resolveRef(refObj.Ref)
	if err != nil {
		return nil, err
	}

	// TODO: may produce circular refs
	pointer, err := g.parseType(qual.NamespaceId, *rawType)
	if err != nil {
		return nil, err
	}
	pointer.NamespaceId = qual.NamespaceId
	pointer.Qual = qual
	pointer.Ref = refObj
	// XML extension from the reference overrides the type definition
	if refObj.Xml != nil {
		pointer.Xml = refObj.Xml
	}
	if refObj.Nullable != nil {
		pointer.Nullable = *refObj.Nullable
	}

	return pointer, nil
}

func (g *Generator) parseType(schemaId string, typeRaw json.RawMessage) (*TypePointer, error) {
	type typeDefSurrogate struct {
		Type string `json:"type"`
		Ref  string `json:"$ref"`
	}
	ts := new(typeDefSurrogate)
	err := json.Unmarshal(typeRaw, ts)
	if err != nil {
		return nil, err
	}

	if ts.Ref != "" {
		return g.parseRef(typeRaw)
	}

	var typeDef TypeDefinition
	switch ts.Type {
	case "string":
		typeDef = new(TypeString)
	case "object":
		typeDef = new(TypeObject)
	case "number":
		typeDef = new(TypeNumber)
	case "integer":
		typeDef = new(TypeInteger)
	case "boolean":
		typeDef = new(TypeBoolean)
	case "array":
		typeDef = new(TypeArray)
	default:
		return nil, fmt.Errorf("unsupported or missing type: %s", ts.Type)
	}

	err = json.Unmarshal(typeRaw, typeDef)
	if err != nil {
		return nil, err
	}

	typePtr := &TypePointer{
		NamespaceId: schemaId,
		Type:        typeDef,
		Qual:        nil,
		Ref:         nil,
		Nullable:    typeDef.GetType().Nullable != nil && *typeDef.GetType().Nullable,
		Xml:         typeDef.GetType().Xml,
		IsBase:      false,
	}

	xmlExt := typeDef.GetType().Xml
	if xmlExt != nil && xmlExt.IsBase {
		typePtr.IsBase = true
	}

	return typePtr, nil
}
