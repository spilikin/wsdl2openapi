package generator

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"sync"

	"github.com/dave/jennifer/jen"
)

type Qual struct {
	PackageName string
	Path        string
	Name        string
}

type TypePointer struct {
	PackageName string
	Type        TypeDefinition
	Xml         *XmlExtension
	Nullable    bool
	Ref         *ReferenceObject
	Qual        *Qual
	IsBase      bool
}

func (tp *TypePointer) IsSameNamespace(other *TypePointer) bool {
	if tp.Xml == nil || other.Xml == nil {
		return false
	}
	return tp.Xml.Namespace == other.Xml.Namespace
}

type Generator struct {
	OutputDir      string
	NamingStrategy NamingStrategy
	Api            *Api
}

// pkgGen tracks per-package state during type generation.
type pkgGen struct {
	file             *jen.File
	needsBase64Bytes bool
}

// isBase64String reports whether t is an XSD base64Binary value, i.e.
// `type: string, format: byte` per OpenAPI conventions.
func isBase64String(t TypeDefinition) bool {
	ts, ok := t.(*TypeString)
	return ok && ts.Format == "byte"
}

// base64BytesTypeName is the name of the per-package helper type that wraps
// []byte and (un)marshals XML element content as base64. Exported so that
// callers in other packages can set fields with `pkg.Base64Bytes(myBytes)`.
const base64BytesTypeName = "Base64Bytes"

func (g *Generator) Validate() error {
	if g.Api == nil {
		return fmt.Errorf("Api is required")
	}
	if g.OutputDir == "" {
		return fmt.Errorf("OutputDir is required")
	}
	// Validate all refs point to existing schemas
	for _, key := range g.Api.Components.Schemas.Keys {
		typeRaw := g.Api.Components.Schemas.Entries[key]
		if err := g.validateRefs(typeRaw); err != nil {
			return fmt.Errorf("invalid reference in %s: %w", key, err)
		}
	}
	return nil
}

// schemaGroup is an ordered grouping of flat component-schema keys by namespace,
// used to drive per-package code generation.
type schemaGroup struct {
	packageName string
	typeNames   []string
}

// groupSchemas partitions the flat components.schemas map into ordered groups
// keyed by namespace identifier (the prefix before SchemaKeySeparator).
func (g *Generator) groupSchemas() ([]*schemaGroup, error) {
	index := make(map[string]*schemaGroup)
	var groups []*schemaGroup
	for _, key := range g.Api.Components.Schemas.Keys {
		pkgName, typeName := SplitSchemaKey(key)
		if pkgName == "" {
			return nil, fmt.Errorf("invalid schema key %q (missing %q separator)", key, SchemaKeySeparator)
		}
		grp, exists := index[pkgName]
		if !exists {
			grp = &schemaGroup{packageName: pkgName}
			index[pkgName] = grp
			groups = append(groups, grp)
		}
		grp.typeNames = append(grp.typeNames, typeName)
	}
	return groups, nil
}

func (g *Generator) validateRefs(raw json.RawMessage) error {
	var obj struct {
		Ref        string                     `json:"$ref"`
		Properties map[string]json.RawMessage `json:"properties"`
		Items      json.RawMessage            `json:"items"`
	}
	if err := json.Unmarshal(raw, &obj); err != nil {
		return nil // Not a valid object, skip
	}
	if obj.Ref != "" {
		if _, _, err := g.resolveRef(obj.Ref); err != nil {
			return err
		}
	}
	for _, prop := range obj.Properties {
		if err := g.validateRefs(prop); err != nil {
			return err
		}
	}
	if obj.Items != nil {
		if err := g.validateRefs(obj.Items); err != nil {
			return err
		}
	}
	return nil
}

func (g *Generator) Generate() error {
	g.ExtractInlineObjects()

	if err := g.Validate(); err != nil {
		return fmt.Errorf("validation failed: %w", err)
	}

	if err := os.MkdirAll(g.OutputDir, 0755); err != nil {
		return err
	}

	if err := g.GenerateTypes(); err != nil {
		return err
	}

	if err := g.GenerateSoap(); err != nil {
		return err
	}

	return nil
}

func (g *Generator) GenerateTypes() error {
	groups, err := g.groupSchemas()
	if err != nil {
		return err
	}
	var wg sync.WaitGroup
	errChan := make(chan error, len(groups))

	for _, grp := range groups {
		wg.Add(1)
		go func(grp *schemaGroup) {
			defer wg.Done()
			if err := g.generatePackageTypes(grp); err != nil {
				errChan <- err
			}
		}(grp)
	}

	wg.Wait()
	close(errChan)

	// Return first error if any
	for err := range errChan {
		return err
	}
	return nil
}

func (g *Generator) generatePackageTypes(grp *schemaGroup) error {
	packageName := grp.packageName
	schemaPath := g.NamingStrategy.FilePath(g.OutputDir, packageName, "types.go")
	err := os.MkdirAll(filepath.Dir(schemaPath), 0755)
	if err != nil {
		return err
	}

	packagePath := g.NamingStrategy.BuildPackagePath(packageName)

	jenFile := jen.NewFilePath(packagePath)

	jenFile.HeaderComment("// Code generated by wsdl2openapi; DO NOT EDIT.")

	pkg := &pkgGen{file: jenFile}

	for _, typeName := range grp.typeNames {
		typeRaw := g.Api.Components.Schemas.Entries[packageName+SchemaKeySeparator+typeName]
		typePtr, err := g.parseType(packageName, typeRaw)
		if err != nil {
			return fmt.Errorf("failed to parse type %s in schema %s: %w", typeName, packageName, err)
		}

		jenFile.Line()

		if t, ok := typePtr.Type.(*TypeObject); ok {
			err := g.renderGlobalObject(pkg, typeName, typePtr, t)
			if err != nil {
				return fmt.Errorf("failed to render struct for type %s in schema %s: %w", typeName, packageName, err)
			}
		} else if typePtr.Type.IsPrimitive() {
			if TypeHasFacets(typePtr.Type.GetType()) {
				g.renderPrimitiveTypeWithFacets(jenFile, typeName, typePtr)
			}
			// skip pure primitive types without facets, as they are rendered inline
		} else {
			return fmt.Errorf("unsupported type definition for type %s in schema %s: %T", typeName, packageName, typePtr.Type)
		}

	}

	if pkg.needsBase64Bytes {
		g.renderBase64BytesType(jenFile)
	}

	err = jenFile.Save(schemaPath)
	if err != nil {
		return fmt.Errorf("failed to save generated types to %s: %w", schemaPath, err)
	}
	return nil
}

func (g *Generator) renderPrimitiveTypeWithFacets(jenFile *jen.File, typeName string, typePtr *TypePointer) {
	primitiveTypeStmt, err := g.golangPrimitiveType(&typePtr.Type)
	if err != nil {
		jenFile.Comment(fmt.Sprintf("Failed to generate primitive type for %s: %v", typeName, err))
		return
	}

	jenFile.Type().Id(typeName).Add(primitiveTypeStmt)

	jenFile.Comment(fmt.Sprintf("Enum values for %s", typeName))
	constDefs := []jen.Code{}
	for _, enumVal := range typePtr.Type.GetType().Enum {
		constName := g.NamingStrategy.EnumValueName(typeName, enumVal)
		constDefs = append(constDefs, jen.Id(constName).Id(typeName).Op("=").Lit(enumVal))
	}
	jenFile.Const().Defs(constDefs...)
	// generate IsValid method to validate if a value is one of the allowed enum values
	isValidFunc := jen.Func().Params(jen.Id("v").Id(typeName)).Id("IsValid").Params().Bool().BlockFunc(func(jg *jen.Group) {
		jg.Switch(jen.Id("v")).BlockFunc(func(jg *jen.Group) {
			for _, enumVal := range typePtr.Type.GetType().Enum {
				constName := g.NamingStrategy.EnumValueName(typeName, enumVal)
				jg.Case(jen.Id(constName)).Return(jen.True())
			}
			jg.Default().Return(jen.False())
		})
	})
	jenFile.Add(isValidFunc)
}

func (g *Generator) renderGlobalObject(pkg *pkgGen, typeName string, typePtr *TypePointer, typeDef *TypeObject) error {

	jenFile := pkg.file
	fields, err := g.renderProperties(pkg, typePtr, typeDef)
	if err != nil {
		return fmt.Errorf("failed to render properties for type %s in package %s: %w", typeName, typePtr.PackageName, err)
	}
	jenFile.Type().Id(typeName).Struct(fields...)

	if typePtr.Xml != nil && len(typePtr.Xml.Extends) > 0 {
		for _, ext := range typePtr.Xml.Extends {
			jenFile.Comment("extends " + ext)
			jenFile.Func().Params(jen.Id(typeName)).Id(g.NamingStrategy.BaseTypeFuncName(ext)).Params().Block()
		}
	}

	if typePtr.IsBase {
		interfaceName := g.NamingStrategy.BaseTypeInterfaceName(typeName)
		funcName := g.NamingStrategy.BaseTypeFuncName(fmt.Sprintf("#/components/schemas/%s%s%s", typePtr.PackageName, SchemaKeySeparator, typeName))
		jenFile.Line()
		jenFile.Comment("Interface for types that extend " + typeName)
		jenFile.Type().Id(interfaceName).Interface(
			jen.Id(funcName).Params(),
		)
		jenFile.Line()
		jenFile.Comment("The type itself implements " + interfaceName)
		jenFile.Func().Params(jen.Id(typeName)).Id(funcName).Params().Block()
	}

	return nil
}

func (g *Generator) renderProperties(pkg *pkgGen, typePtr *TypePointer, typeDef *TypeObject) ([]jen.Code, error) {
	var fieldDefs []jen.Code

	if typePtr.Xml != nil && typePtr.Xml.Name != "" {
		x := jen.Id("XMLName").Qual("encoding/xml", "Name").Tag(map[string]string{
			"xml": fmt.Sprintf("%s %s", typePtr.Xml.Namespace, typePtr.Xml.Name),
		})
		fieldDefs = append(fieldDefs, x)
	}

	requiredSet := make(map[string]bool, len(typeDef.Required))
	for _, name := range typeDef.Required {
		requiredSet[name] = true
	}

	for _, propName := range typeDef.Properties.Keys {
		propTypeRaw := typeDef.Properties.Entries[propName]
		propType, err := g.parseType(typePtr.PackageName, propTypeRaw)
		if err != nil {
			return nil, fmt.Errorf("failed to parse property %s in package %s: %w", propName, typePtr.PackageName, err)
		}
		// Optionality: a property is optional unless it appears in the parent's required list.
		propType.Nullable = !requiredSet[propName]
		propertyCode, err := g.renderProperty(pkg, typePtr, propName, propType)
		if err != nil {
			return nil, fmt.Errorf("failed to render property %s in package %s: %w", propName, typePtr.PackageName, err)
		}
		fieldDefs = append(fieldDefs, propertyCode)
	}

	return fieldDefs, nil
}

func (g *Generator) renderProperty(pkg *pkgGen, baseTypePtr *TypePointer, propName string, propTypePtr *TypePointer) (jen.Code, error) {
	fieldName := g.NamingStrategy.PublicIdentifier(propName)

	stmt := jen.Id(fieldName)

	return g.renderPropertyTypeAndTags(pkg, stmt, baseTypePtr, propTypePtr)
}

func (g *Generator) renderPropertyTypeAndTags(pkg *pkgGen, stmt *jen.Statement, baseTypePtr, propTypePtr *TypePointer) (*jen.Statement, error) {
	isArray := false
	if typeArray, ok := propTypePtr.Type.(*TypeArray); ok {
		stmt = stmt.Op("[]")
		itemsTypePtr, err := g.parseType(propTypePtr.PackageName, typeArray.Items)
		if err != nil {
			return nil, err
		}
		propTypePtr = itemsTypePtr
		isArray = true
	}

	xmlExt := propTypePtr.Xml
	var xmlTag []string

	// create XML tag from xml extension
	if xmlExt != nil && xmlExt.Name != "" {
		if xmlExt.Namespace != "" && !baseTypePtr.IsSameNamespace(propTypePtr) {
			xmlTag = append(xmlTag, xmlExt.Namespace+" "+xmlExt.Name)
		} else {
			xmlTag = append(xmlTag, xmlExt.Name)
		}
		if xmlExt.Attribute {
			xmlTag = append(xmlTag, "attr")
		}
	}

	addOmitempty := func() {
		if propTypePtr.Nullable && len(xmlTag) > 0 {
			xmlTag = append(xmlTag, "omitempty")
		}
	}

	propType := propTypePtr.Type

	if propTypePtr.Qual != nil {
		// add pointer only for non-array, nullable, non-base, non-primitive types
		if propTypePtr.Nullable && !isArray && !propTypePtr.IsBase && !propType.IsPrimitive() {
			stmt = stmt.Op("*")
			addOmitempty()
		} else if propTypePtr.Nullable && propTypePtr.Type.IsPrimitive() {
			addOmitempty()
		}
		if propTypePtr.IsBase {
			interfaceName := g.NamingStrategy.BaseTypeInterfaceName(propTypePtr.Qual.Name)
			stmt = stmt.Qual(propTypePtr.Qual.Path, interfaceName)
		} else if isBase64String(propType) {
			pkg.needsBase64Bytes = true
			stmt = stmt.Id(base64BytesTypeName)
		} else if propType.IsPrimitive() && !TypeHasFacets(propType.GetType()) {
			primitiveTypeStmt, err := g.golangPrimitiveType(&propType)
			if err != nil {
				return nil, err
			}
			stmt = stmt.Add(primitiveTypeStmt)
		} else {
			stmt = stmt.Qual(propTypePtr.Qual.Path, propTypePtr.Qual.Name)
		}
	} else {
		switch t := propType.(type) {
		case *TypeString:
			if t.Format == "byte" {
				pkg.needsBase64Bytes = true
				stmt = stmt.Id(base64BytesTypeName)
			} else {
				stmt = stmt.String()
				if t.Format == "chardata" {
					xmlTag = append(xmlTag, "chardata")
				}
			}
		case *TypeNumber:
			stmt = stmt.Float64()
		case *TypeInteger:
			stmt = stmt.Int()
		case *TypeBoolean:
			stmt = stmt.Bool()
		case *TypeObject:
			fields, err := g.renderProperties(pkg, propTypePtr, t)
			if err != nil {
				return nil, err
			}
			if !isArray && propTypePtr.Nullable {
				stmt = stmt.Op("*")
			}
			stmt = stmt.Struct(fields...)
		default:
			return nil, fmt.Errorf("unsupported property type: %T", propType)
		}
		if !isArray && propTypePtr.Nullable {
			addOmitempty()
		}
	}

	tag := make(map[string]string)
	if len(xmlTag) > 0 {
		tag["xml"] = strings.Join(xmlTag, ",")
	}

	stmt = stmt.Tag(tag)

	return stmt, nil
}

// renderBase64BytesType emits a private base64Bytes type plus XML
// (un)marshalers that base64-encode/decode the element's character data.
// Called once per package when at least one property has format: byte.
func (g *Generator) renderBase64BytesType(f *jen.File) {
	f.Line()
	f.Type().Id(base64BytesTypeName).Index().Byte()

	f.Line()
	f.Func().Params(jen.Id("b").Op("*").Id(base64BytesTypeName)).Id("UnmarshalXML").Params(
		jen.Id("d").Op("*").Qual("encoding/xml", "Decoder"),
		jen.Id("start").Qual("encoding/xml", "StartElement"),
	).Error().Block(
		jen.Var().Id("s").String(),
		jen.If(
			jen.Err().Op(":=").Id("d").Dot("DecodeElement").Call(jen.Op("&").Id("s"), jen.Op("&").Id("start")),
			jen.Err().Op("!=").Nil(),
		).Block(
			jen.Return(jen.Err()),
		),
		jen.List(jen.Id("decoded"), jen.Err()).Op(":=").Qual("encoding/base64", "StdEncoding").Dot("DecodeString").Call(jen.Id("s")),
		jen.If(jen.Err().Op("!=").Nil()).Block(
			jen.Return(jen.Err()),
		),
		jen.Op("*").Id("b").Op("=").Id("decoded"),
		jen.Return(jen.Nil()),
	)

	f.Line()
	f.Func().Params(jen.Id("b").Id(base64BytesTypeName)).Id("MarshalXML").Params(
		jen.Id("e").Op("*").Qual("encoding/xml", "Encoder"),
		jen.Id("start").Qual("encoding/xml", "StartElement"),
	).Error().Block(
		jen.Return(jen.Id("e").Dot("EncodeElement").Call(
			jen.Qual("encoding/base64", "StdEncoding").Dot("EncodeToString").Call(jen.Id("b")),
			jen.Id("start"),
		)),
	)
}

func (g *Generator) golangPrimitiveType(primitiveType *TypeDefinition) (jen.Code, error) {
	switch t := (*primitiveType).(type) {
	case *TypeString:
		return jen.String(), nil
	case *TypeInteger:
		return jen.Int(), nil
	case *TypeNumber:
		return jen.Float64(), nil
	case *TypeBoolean:
		return jen.Bool(), nil
	default:
		return nil, fmt.Errorf("unsupported primitive type: %T", t)
	}
}

func (g *Generator) resolveRef(ref string) (*Qual, json.RawMessage, error) {
	if !strings.HasPrefix(ref, "#/components/schemas/") {
		return nil, nil, fmt.Errorf("unsupported ref format: %s", ref)
	}
	key := ref[len("#/components/schemas/"):]
	rawType, ok := g.Api.Components.Schemas.Entries[key]
	if !ok {
		return nil, nil, fmt.Errorf("schema not found: %s", key)
	}
	packageName, typeName := SplitSchemaKey(key)
	if packageName == "" {
		return nil, nil, fmt.Errorf("invalid ref format: %s (missing %q separator)", ref, SchemaKeySeparator)
	}

	qual := &Qual{
		PackageName: packageName,
		Path:        g.NamingStrategy.BuildPackagePath(packageName),
		Name:        typeName,
	}

	return qual, rawType, nil
}

func (g *Generator) parseRef(raw json.RawMessage) (*TypePointer, error) {
	refObj := new(ReferenceObject)
	err := json.Unmarshal(raw, refObj)
	if err != nil {
		return nil, err
	}
	qual, rawType, err := g.resolveRef(refObj.Ref)
	if err != nil {
		return nil, err
	}

	pointer, err := g.parseType(qual.PackageName, rawType)
	if err != nil {
		return nil, err
	}

	pointer.PackageName = qual.PackageName
	pointer.Qual = qual
	pointer.Ref = refObj
	// XML extension from the reference overrides the type definition
	if refObj.Xml != nil {
		pointer.Xml = refObj.Xml
		if refObj.Xml.IsBase {
			pointer.IsBase = true
		} else {
			pointer.IsBase = false
		}
	}
	// Optionality (Nullable) is set by the caller based on the parent's
	// `required` list — see renderProperties.

	return pointer, nil
}

func (g *Generator) parseType(schemaId string, typeRaw json.RawMessage) (*TypePointer, error) {
	type typeDefSurrogate struct {
		Type string `json:"type"`
		Ref  string `json:"$ref"`
	}
	ts := new(typeDefSurrogate)
	err := json.Unmarshal(typeRaw, ts)
	if err != nil {
		return nil, err
	}

	if ts.Ref != "" {
		return g.parseRef(typeRaw)
	}

	var typeDef TypeDefinition
	switch ts.Type {
	case "string":
		typeDef = new(TypeString)
	case "object":
		typeDef = new(TypeObject)
	case "number":
		typeDef = new(TypeNumber)
	case "integer":
		typeDef = new(TypeInteger)
	case "boolean":
		typeDef = new(TypeBoolean)
	case "array":
		typeDef = new(TypeArray)
	default:
		return nil, fmt.Errorf("unsupported or missing type: %s", ts.Type)
	}

	err = json.Unmarshal(typeRaw, typeDef)
	if err != nil {
		return nil, err
	}

	typePtr := &TypePointer{
		PackageName: schemaId,
		Type:        typeDef,
		Qual:        nil,
		Ref:         nil,
		// Nullable is set by callers (renderProperties) based on the
		// parent object's `required` list. Top-level types are never
		// "optional" in isolation.
		Nullable: false,
		Xml:      typeDef.GetType().Xml,
		IsBase:   false,
	}

	xmlExt := typeDef.GetType().Xml
	if xmlExt != nil && xmlExt.IsBase {
		typePtr.IsBase = true
	}

	return typePtr, nil
}
