package generator

import (
	"fmt"
	"log/slog"
	"os"
	"path/filepath"

	"github.com/dave/jennifer/jen"
)

var xmlNameEnvelope11 = jen.Id("XMLName").Qual("encoding/xml", "Name").Tag(map[string]string{"xml": "http://schemas.xmlsoap.org/soap/envelope/ Envelope"})
var xmlNameEnvelope12 = jen.Id("XMLName").Qual("encoding/xml", "Name").Tag(map[string]string{"xml": "http://www.w3.org/2003/05/soap-envelope Envelope"})

func soap11FaultFields() []jen.Code {
	return []jen.Code{
		jen.Id("Code").String().Tag(map[string]string{"xml": "faultcode"}),
		jen.Id("String").String().Tag(map[string]string{"xml": "faultstring"}),
		jen.Id("Actor").String().Tag(map[string]string{"xml": "faultactor"}),
	}
}

func renderFaultStruct(detailField jen.Code) jen.Code {
	fields := soap11FaultFields()
	if detailField != nil {
		fields = append(fields, detailField)
	}
	return jen.Id("Fault").Op("*").Struct(fields...).Tag(map[string]string{"xml": "Body>Fault"})
}

type soapContext struct {
	service *WebService
	port    *WebServicePort
	op      *OperationDefinition
	msg     *WebServiceMessage
}

func (g *Generator) GenerateSoap() error {
	if g.Api.WebServices == nil {
		return nil
	}
	ctx := &soapContext{}
	for _, ws := range g.Api.WebServices {
		ctx.service = &ws
		if err := g.renderService(ctx); err != nil {
			return err
		}
	}

	return nil
}

func (g *Generator) renderService(ctx *soapContext) error {
	for _, port := range ctx.service.Ports {
		ctx.port = &port

		portPackage := g.NamingStrategy.PackageForPort(ctx.service, &port)
		filename := g.NamingStrategy.FilePath(g.OutputDir, portPackage, "soap.go")

		slog.Info("Generating SOAP port", "service", ctx.service.Name, "port", ctx.port.Name, "package", portPackage, "filename", filename)

		err := os.MkdirAll(filepath.Dir(filename), 0755)
		if err != nil {
			return err
		}

		packagePath := g.NamingStrategy.BuildPackagePath(portPackage)
		jenFile := jen.NewFilePath(packagePath)

		jenFile.HeaderComment("// Code generated by wsdl2openapi go generator. DO NOT EDIT.")

		if err := g.renderPort(jenFile, ctx); err != nil {
			return err
		}

		if err := jenFile.Save(filename); err != nil {
			return err
		}
	}
	return nil
}

func (g *Generator) renderOperationTypeStruct(jenFile *jen.File, ctx *soapContext) error {
	// generate private struct we will use to duck type for external usage without dependency on the generator package,
	// since we cannot use the OperationDefinition struct directly due to the WebServiceMessage fields which contain raw XML that needs to be parsed and cannot be easily represented in a way that is useful for external users of the generated code
	jenFile.Type().Id("soapOperation").Struct(
		jen.Id("name").String(),
		jen.Id("soapAction").String(),
		jen.Id("bindingType").String(),
	)
	jenFile.Line()
	// add duck type functions to access private fields
	jenFile.Func().Params(jen.Id("op").Op("*").Id("soapOperation")).Id("Name").Params().String().Block(
		jen.Return(jen.Id("op").Dot("name")),
	)
	jenFile.Line()
	jenFile.Func().Params(jen.Id("op").Op("*").Id("soapOperation")).Id("SOAPAction").Params().String().Block(
		jen.Return(jen.Id("op").Dot("soapAction")),
	)
	jenFile.Line()
	jenFile.Func().Params(jen.Id("op").Op("*").Id("soapOperation")).Id("BindingType").Params().String().Block(
		jen.Return(jen.Id("op").Dot("bindingType")),
	)
	jenFile.Line()
	return nil
}

func (g *Generator) renderPort(jenFile *jen.File, ctx *soapContext) error {
	if err := g.renderOperationTypeStruct(jenFile, ctx); err != nil {
		return err
	}
	for _, operation := range ctx.port.Operations {
		slog.Info("Generating SOAP operation", "operation", operation.Name)
		ctx.op = &operation

		jenFile.Var().Id(g.NamingStrategy.OperationVarName(&operation)).Op("=").Id("soapOperation").Values(
			jen.Dict{
				jen.Id("name"):        jen.Lit(operation.Name),
				jen.Id("soapAction"):  jen.Lit(operation.SOAPAction),
				jen.Id("bindingType"): jen.Lit(string(ctx.port.BindingType)),
			},
		)
		jenFile.Line()

		switch ctx.port.BindingType {
		case SOAP11:
			if err := g.renderOperation11(jenFile, ctx); err != nil {
				return err
			}
		default:
			slog.Warn("Unknown SOAP binding type", "bindingType", ctx.port.BindingType)
		}
	}
	return nil
}

func (g *Generator) renderOperation11(jenFile *jen.File, ctx *soapContext) error {

	if err := g.renderEnvelopes11(jenFile, ctx); err != nil {
		return err
	}

	return nil
}

func (g *Generator) renderEnvelopes11(jenFile *jen.File, ctx *soapContext) error {

	inputEnvelopeName := g.NamingStrategy.InputEnvelopeName(ctx.op)

	if len(ctx.op.Input.SOAPHeaders) > 0 {
		slog.Warn("Generator does not support SOAP headers, but operation has headers defined. Headers will be ignored.", "operation", ctx.op.Name)
	}

	inputBodyType, err := g.resolveRefToPointer(ctx.op.Input.SOAPBody)
	if err != nil {
		return fmt.Errorf("failed to resolve input SOAP body reference for operation %s: %w", ctx.op.Name, err)
	}

	inputBodyXmlTag := map[string]string{"xml": fmt.Sprintf("Body>%s", inputBodyType.Xml.Name)}

	jenFile.Type().Id(inputEnvelopeName).Struct(
		xmlNameEnvelope11,
		jen.Id(inputBodyType.Qual.Name).Op("*").Qual(inputBodyType.Qual.Path, inputBodyType.Qual.Name).Tag(inputBodyXmlTag),
	)
	jenFile.Line()

	// render IsFault method for input envelope, which always returns false since faults can only be returned in response envelopes
	jenFile.Func().Params(jen.Id("e").Op("*").Id(inputEnvelopeName)).Id("IsFault").Params().Bool().Block(
		jen.Return(jen.False()),
	)
	jenFile.Line()

	// generate output envelope
	outputEnvelopeName := g.NamingStrategy.OutputEnvelopeName(ctx.op)

	outputBodyType, err := g.resolveRefToPointer(ctx.op.Output.SOAPBody)
	if err != nil {
		return fmt.Errorf("failed to resolve output SOAP body reference for operation %s: %w", ctx.op.Name, err)
	}

	outputBodyXmlTag := map[string]string{"xml": fmt.Sprintf("Body>%s", outputBodyType.Xml.Name)}

	// fault detail code generation
	var faultDetailField jen.Code

	// we only support custom faults with one fault definition,
	if len(ctx.op.Faults) > 1 {
		slog.Warn("Generator does not support multiple SOAP faults, but operation has multiple faults defined. Only the first fault will be generated.", "operation", ctx.op.Name, "faultCount", len(ctx.op.Faults))
	}

	_, faultMessage, hasFault := firstValueFromMap(ctx.op.Faults)
	if hasFault {
		faultType, err := g.resolveRefToPointer(faultMessage.SOAPBody)
		if err != nil {
			return fmt.Errorf("failed to resolve SOAP fault reference for operation %s: %w", ctx.op.Name, err)
		}
		faultXmlTag := map[string]string{"xml": fmt.Sprintf("Detail>%s", faultType.Xml.Name)}

		slog.Info("Generating SOAP fault for operation", "operation", ctx.op.Name, "faultType", faultType)
		faultDetailField = jen.Id("Detail").Op("*").Qual(faultType.Qual.Path, faultType.Qual.Name).Tag(faultXmlTag)
	} else {
		slog.Info("Generating generic SOAP fault for operation", "operation", ctx.op.Name)
	}

	faultCode := renderFaultStruct(faultDetailField)

	jenFile.Type().Id(outputEnvelopeName).Struct(
		xmlNameEnvelope11,
		jen.Id(outputBodyType.Qual.Name).Op("*").Qual(outputBodyType.Qual.Path, outputBodyType.Qual.Name).Tag(outputBodyXmlTag),
		faultCode,
	)
	jenFile.Line()

	// render IsFault method for output envelope
	jenFile.Func().Params(jen.Id("e").Op("*").Id(outputEnvelopeName)).Id("IsFault").Params().Bool().Block(
		jen.Return(jen.Id("e").Dot("Fault").Op("!=").Nil()),
	)
	jenFile.Line()

	return nil
}

func (g *Generator) resolveRefToPointer(ref string) (*TypePointer, error) {
	qual, rawType, err := g.resolveRef(ref)
	if err != nil {
		return nil, err
	}
	ptr, err := g.parseType(qual.PackageName, rawType)
	if err != nil {
		return nil, fmt.Errorf("failed to parse type for reference %s: %w", ref, err)
	}
	ptr.Qual = qual
	return ptr, nil
}

func (g *Generator) renderEnvelopes12(jenFile *jen.File, ctx *soapContext) error {
	inputEnvelopeName := g.NamingStrategy.InputEnvelopeName(ctx.op)

	jenFile.Type().Id(inputEnvelopeName).Struct(
		xmlNameEnvelope12,
	)

	outputEnvelopeName := g.NamingStrategy.OutputEnvelopeName(ctx.op)
	jenFile.Type().Id(outputEnvelopeName).Struct(
		xmlNameEnvelope12,
	)

	return nil
}

func firstValueFromMap[T any](m map[string]T) (string, T, bool) {
	for k, v := range m {
		return k, v, true
	}
	var zero T
	return "", zero, false
}
