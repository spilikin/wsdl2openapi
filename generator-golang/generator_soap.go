package main

import (
	"log/slog"
	"os"
	"path/filepath"

	"github.com/dave/jennifer/jen"
)

var xmlNameEnvelope11 = jen.Id("XMLName").Qual("encoding/xml", "Name").Tag(map[string]string{"xml": "http://schemas.xmlsoap.org/soap/envelope/ Envelope"})
var xmlNameEnvelope12 = jen.Id("XMLName").Qual("encoding/xml", "Name").Tag(map[string]string{"xml": "http://www.w3.org/2003/05/soap-envelope Envelope"})

type soapContext struct {
	service *WebService
	port    *WebServicePort
	op      *OperationDefinition
	msg     *WebServiceMessage
}

func (g *Generator) GenerateSoap() error {
	if g.Api.WebServices == nil {
		return nil
	}
	ctx := &soapContext{}
	for _, ws := range g.Api.WebServices {
		ctx.service = &ws
		for _, port := range ws.Ports {
			ctx.port = &port

			if port.BindingType == SOAP11 {

			}

			portPackage := g.NamingStrategy.PackageForPort(&ws, &port)
			filename := g.NamingStrategy.FilePath(g.OutputDir, portPackage, "soap.go")

			slog.Info("Generating SOAP port", "service", ws.Name, "port", port.Name, "package", portPackage, "filename", filename)

			err := os.MkdirAll(filepath.Dir(filename), 0755)
			if err != nil {
				return err
			}

			packagePath := g.NamingStrategy.BuildPackagePath(portPackage)
			jenFile := jen.NewFilePath(packagePath)

			jenFile.HeaderComment("// Code generated by wsdl2openapi. DO NOT EDIT.")

			if err := g.renderPort(jenFile, ctx); err != nil {
				return err
			}

			if err := jenFile.Save(filename); err != nil {
				return err
			}
		}
	}

	return nil
}

func (g *Generator) renderPort(jenFile *jen.File, ctx *soapContext) error {
	for _, operation := range ctx.port.Operations {
		slog.Info("Generating SOAP operation", "operation", operation.Name)
		ctx.op = &operation
		if err := g.renderOperation(jenFile, ctx); err != nil {
			return err
		}
	}
	return nil
}

